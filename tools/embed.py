#!/usr/bin/env python3
"""Turns the bridge payload (a COFF object) into a C header with the entry
point offsets.

The raw .text bytes are taken straight from the object file. (llvm-objcopy
-O binary does not support COFF: it writes the whole object, headers
included, which puts the code at the wrong offsets.)

Fails if the payload is not a single relocation-free .text section."""
import struct, sys

obj, out = sys.argv[1:3]
o = open(obj, "rb").read()
machine, nsec, _, symptr, nsym, optsize, _ = struct.unpack_from("<HHIIIHH", o, 0)
if machine != 0x8664:
    sys.exit("embed: %s is not an x86-64 COFF object" % obj)

def fail(msg):
    sys.exit("embed: " + msg + " - the bridge payload must be one position-independent .text section")

strtab = symptr + nsym * 18
def name_of(raw):
    if raw[:4] == b"\0\0\0\0":            # long name: offset into the string table
        off = struct.unpack_from("<I", raw, 4)[0]
        return o[strtab + off:o.index(b"\0", strtab + off)].decode()
    return raw.rstrip(b"\0").decode()

text = None
text_index = None
for i in range(nsec):
    s = 20 + optsize + i * 40
    name = o[s:s + 8].rstrip(b"\0").decode()
    size, ptr, relptr, _, nrel, _, flags = struct.unpack_from("<IIIIHHI", o, s + 16)
    if name == ".text":
        if nrel:
            fail("%d relocation(s) in .text" % nrel)
        text, text_index = o[ptr:ptr + size], i + 1
    elif size and not (flags & 0x800):    # anything with content that is not IMAGE_SCN_LNK_REMOVE
        fail("section %s has %d bytes" % (name, size))
if text is None:
    fail("no .text section")

syms = {}
i = 0
while i < nsym:
    e = symptr + i * 18
    value, secnum = struct.unpack_from("<Ih", o, e + 8)
    sclass, naux = o[e + 16], o[e + 17]
    if secnum == text_index and sclass == 2:   # external symbol in .text
        syms[name_of(o[e:e + 8])] = value
    i += 1 + naux
for need in ("bridge_init", "bridge_loop"):
    if need not in syms:
        fail("symbol %s not found" % need)

with open(out, "w") as f:
    f.write("/* generated by tools/embed.py - do not edit */\n")
    f.write("#define PAYLOAD_INIT_OFFSET 0x%X\n" % syms["bridge_init"])
    f.write("#define PAYLOAD_LOOP_OFFSET 0x%X\n" % syms["bridge_loop"])
    f.write("static const unsigned char g_payload[%d] = {\n" % len(text))
    for i in range(0, len(text), 16):
        f.write("    " + ", ".join("0x%02X" % b for b in text[i:i + 16]) + ",\n")
    f.write("};\n")
print("payload: %d bytes, bridge_init at 0x%X, bridge_loop at 0x%X" % (len(text), syms["bridge_init"], syms["bridge_loop"]))
