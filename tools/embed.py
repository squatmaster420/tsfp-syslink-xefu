#!/usr/bin/env python3
"""Turns the bridge payload into a C header with the entry point offsets."""
import subprocess, sys
obj, binf, out = sys.argv[1:4]
syms = {}
for line in subprocess.run(["llvm-nm", obj], capture_output=True, text=True, check=True).stdout.splitlines():
    parts = line.split()
    if len(parts) == 3 and parts[1] in "Tt":
        syms[parts[2]] = int(parts[0], 16)
data = open(binf, "rb").read()
with open(out, "w") as f:
    f.write("/* generated by tools/embed.py - do not edit */\n")
    f.write("#define PAYLOAD_INIT_OFFSET 0x%X\n" % syms["bridge_init"])
    f.write("#define PAYLOAD_LOOP_OFFSET 0x%X\n" % syms["bridge_loop"])
    f.write("static const unsigned char g_payload[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02X" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n")
